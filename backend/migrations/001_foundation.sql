-- Foundation: users, sessions, conversations, membership, messages.

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE users (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email         citext NOT NULL UNIQUE,
  username      citext NOT NULL UNIQUE,
  full_name     text   NOT NULL,
  password_hash text   NOT NULL,
  avatar_url    text,
  -- Opaque code behind a personal invite link. Rotatable, so a leaked link can be killed.
  invite_code   text   NOT NULL UNIQUE,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Server-side sessions. The cookie holds a random token; only its SHA-256 is stored,
-- so a database leak does not hand out usable sessions, and logout really revokes.
CREATE TABLE sessions (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id      uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash   bytea NOT NULL UNIQUE,
  user_agent   text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  expires_at   timestamptz NOT NULL
);
CREATE INDEX sessions_user_idx ON sessions (user_id);
CREATE INDEX sessions_expires_idx ON sessions (expires_at);

CREATE TABLE conversations (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  type       text NOT NULL CHECK (type IN ('dm', 'group')),
  name       text,
  avatar_url text,
  created_by uuid REFERENCES users(id) ON DELETE SET NULL,
  -- For DMs: "<lower uuid>:<higher uuid>", unique, so two people share exactly one DM.
  dm_key     text UNIQUE,
  -- last_seq orders messages. rev counts every change (new message, edit, delete, ...)
  -- and is what clients use to ask "what did I miss?". Both are bumped while holding
  -- this row's lock, so they are assigned in commit order.
  last_seq   bigint NOT NULL DEFAULT 0,
  rev        bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_message_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((type = 'dm') = (dm_key IS NOT NULL)),
  CHECK (type = 'dm' OR name IS NOT NULL)
);

CREATE TABLE conversation_members (
  conversation_id uuid NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  user_id         uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role            text NOT NULL DEFAULT 'member' CHECK (role IN ('admin', 'member')),
  last_read_seq   bigint NOT NULL DEFAULT 0,
  joined_at       timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (conversation_id, user_id)
);
-- "Which conversations am I in?" is the hottest membership query.
CREATE INDEX conversation_members_user_idx ON conversation_members (user_id);

CREATE TABLE messages (
  -- Generated by the client, so a retried send is recognised and never duplicated.
  id              uuid PRIMARY KEY,
  conversation_id uuid NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  seq             bigint NOT NULL,
  rev             bigint NOT NULL,
  sender_id       uuid REFERENCES users(id) ON DELETE SET NULL,
  kind            text NOT NULL DEFAULT 'user' CHECK (kind IN ('user', 'system')),
  text            text,
  image_url       text,
  reply_to_id     uuid REFERENCES messages(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  edited_at       timestamptz,
  deleted_at      timestamptz,
  UNIQUE (conversation_id, seq)
);
-- History pages and "after seq N" use the UNIQUE (conversation_id, seq) index.
-- Catch-up after a reconnect asks for everything changed since a rev.
CREATE INDEX messages_conversation_rev_idx ON messages (conversation_id, rev);
